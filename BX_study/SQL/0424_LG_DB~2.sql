SELECT * 
  FROM ( 
        SELECT PRODUCT_ID
            , PRODUCT_NAME 
          , CATEGORY_NAME
          , PRICE 
          , STOCK_QTY
          , CREATED_AT 
        FROM LG_PRODUCT  
      ORDER BY PRICE DESC 
      )
WHERE ROWNUM <= 3 ; 
        
