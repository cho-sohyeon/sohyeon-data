SELECT * 
    FROM ( 
        SELECT MEMBER_ID 
            , SUM(USE_AMOUNT_KWH) AS 회원별전력합계 
        FROM LG_ENERGY_USAGE_DAILY_FACT 
        GROUP BY MEMBER_ID 
        ORDER BY SUM(USE_AMOUNT_KWH) DESC
        ) 
WHERE ROWNUM <= 3 ; 

